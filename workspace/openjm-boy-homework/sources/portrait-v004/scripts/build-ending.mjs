import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),ending=path.join(root,'ending');
const css=await Promise.all(['src/styles/features/dashboard/DashboardLoadingOverlay.module.css','src/styles/components/BrandMark/BrandMark.module.css'].map(p=>readFile(path.join(ending,'original-assets',p),'utf8')));
const template=await readFile(path.join(ending,'source/index.html.in'),'utf8');
await writeFile(path.join(ending,'index.html'),template.replace('__PRODUCTION_CSS__',css.join('\n').replace(/\b(?:transition|animation):[^;]+;/g,'')).replaceAll('__DURATION__','5.16').replace('__FADE_START__',String(244/60)));
await build({entryPoints:[path.join(ending,'source/runtime.ts')],bundle:true,platform:'browser',format:'iife',outfile:path.join(ending,'runtime.js'),sourcemap:true,target:'es2022'});
console.log('Built native 1080 x 1920 ending; 60 Hz simulation sampled at 25 fps.');
